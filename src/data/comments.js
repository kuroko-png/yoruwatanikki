// コメントの文（例：commentText(0, 0) → 「グラディウスが強い」）
export const commentText = (t, w) => (COMMENT_TEMPLATES[t] || '').replace('◯◯', (COMMENT_WORDS[w] || [''])[0]);
// 2つの文をつなぐ言葉（本編と同じ10個。最後の「、」は、ただ続けるだけ）
export const COMMENT_CONJ = ['そして', 'あるいは', 'しかし', 'だから', 'つまり', 'ただし', 'ところで', 'いわば', 'なおさら', '、'];
// 選ぶ画面に出す文の型（前に作った12個は出さない）
export const COMMENT_T_START = 12;
// つないだ文（例：「この先、強敵があるぞ しかし 回復を試せ」）。c が -1 のときは1文だけ
export const commentFull = (t, w, c = -1, t2 = -1, w2 = -1) => {
  const a = commentText(t, w);
  if (!(c >= 0) || !COMMENT_CONJ[c] || !COMMENT_TEMPLATES[t2] || !COMMENT_WORDS[w2]) return a;
  const j = COMMENT_CONJ[c];
  return j === '、' ? `${a}、${commentText(t2, w2)}` : `${a} ${j} ${commentText(t2, w2)}`;
};
